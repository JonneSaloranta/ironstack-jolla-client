#!/usr/bin/env python3
"""Generate qml/js/content.js and qml/js/content_texts.js - translations for
IronStack's built-in content.

IronStack stores built-in content in English and translates it only when
rendering a web page: the strings are listed in apps/*/i18n_content.py so
`makemessages` puts them in locale/<lang>/LC_MESSAGES/django.po, and the
templates run each value through that catalog (`{% trans exercise.name %}`).
The API returns the stored English values, so the app ships the same
translations to show what the web shows.

- content.js: names and other short texts (lists named *_NAMES or
  ROUTINE_TEXTS) - loaded with the app.
- content_texts.js: long texts (*_INSTRUCTIONS, *_DESCRIPTIONS) - loaded
  only by the pages that show them.

Re-run after an IronStack update that adds content or translations:

    python3 -I tools/content-i18n/generate.py ../IronStack

Only reads the IronStack checkout; nothing there is imported or executed.
"""

import ast
import json
import pathlib
import sys

CONTENT_MODULES = [
    "apps/exercises/i18n_content.py",
    "apps/programs/i18n_content.py",
    "apps/measurements/i18n_content.py",
    "apps/activities/i18n_content.py",
    "apps/stretching/i18n_content.py",
    "apps/nutrition/i18n_content.py",
]
JS_DIR = pathlib.Path(__file__).resolve().parents[2] / "qml" / "js"


def is_short(list_name):
    return list_name.endswith("_NAMES") or list_name == "ROUTINE_TEXTS"


def is_long(list_name):
    return list_name.endswith("_INSTRUCTIONS") or list_name.endswith("_DESCRIPTIONS")


def msgids(module_path, wanted_list):
    """Every string literal passed to _() in the module's top-level lists
    whose name `wanted_list` accepts, in order."""
    tree = ast.parse(module_path.read_text(encoding="utf-8"))
    found = []
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        names = [t.id for t in node.targets if isinstance(t, ast.Name)]
        if not any(wanted_list(name) for name in names):
            continue
        for call in ast.walk(node.value):
            if (
                isinstance(call, ast.Call)
                and isinstance(call.func, ast.Name)
                and call.func.id == "_"
                and call.args
                and isinstance(call.args[0], ast.Constant)
                and isinstance(call.args[0].value, str)
            ):
                found.append(call.args[0].value)
    return found


def unquote(line):
    # A .po string is a C-style quoted literal; JSON's escapes cover the
    # ones gettext writes (\" \\ \n \t).
    return json.loads(line)


def read_po(path):
    """{msgid: msgstr} for translated, non-fuzzy, singular entries without
    a context - content is translated with plain gettext, so a "navigation"
    "Back" (Takaisin) must not replace the muscle group "Back" (Selkä)."""
    catalog = {}
    entry = {}
    field = None
    fuzzy = False

    def flush():
        msgid = entry.get("msgid")
        msgstr = entry.get("msgstr")
        if msgid and msgstr and not fuzzy and "msgid_plural" not in entry and "msgctxt" not in entry:
            catalog[msgid] = msgstr

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line:
            flush()
            entry, field, fuzzy = {}, None, False
        elif line.startswith("#,"):
            fuzzy = fuzzy or "fuzzy" in line
        elif line.startswith("#"):
            continue
        elif line.startswith('"'):
            if field:
                entry[field] += unquote(line)
        else:
            keyword, _, rest = line.partition(" ")
            field = keyword
            entry[field] = unquote(rest)
    flush()
    return catalog


def collect(root, wanted_list):
    wanted = []
    for module in CONTENT_MODULES:
        for msgid in msgids(root / module, wanted_list):
            if msgid not in wanted:
                wanted.append(msgid)
    return wanted


def write(root, filename, what, wanted, catalogs):
    languages = {}
    for language, catalog in catalogs.items():
        translated = {m: catalog[m] for m in wanted if catalog.get(m) and catalog[m] != m}
        if translated:
            languages[language] = translated
    version = (root / "VERSION").read_text(encoding="utf-8").strip()
    body = json.dumps(languages, ensure_ascii=False, indent=1, sort_keys=True)
    path = JS_DIR / filename
    path.write_text(
        ".pragma library\n\n"
        f"// Generated by tools/content-i18n/generate.py from IronStack {version} - do not edit.\n"
        f"// {what} as the IronStack web shows them, by language.\n\n"
        "var catalog = " + body + "\n",
        encoding="utf-8",
    )
    counts = ", ".join(f"{lang} {len(texts)}" for lang, texts in languages.items())
    print(f"{path}: {len(wanted)} texts; {counts}")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    catalogs = {
        po.parts[-3]: read_po(po)
        for po in sorted(root.glob("locale/*/LC_MESSAGES/django.po"))
        if po.parts[-3] != "en"
    }
    write(root, "content.js", "Built-in content names", collect(root, is_short), catalogs)
    write(root, "content_texts.js", "Built-in instructions and descriptions",
          collect(root, is_long), catalogs)


if __name__ == "__main__":
    main()
