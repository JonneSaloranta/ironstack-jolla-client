#!/usr/bin/env python3
"""Generate qml/js/content.js - translations for IronStack's built-in
content names (exercises, muscle groups, equipment, programs, workouts).

IronStack stores built-in content in English and translates it only when
rendering a web page: the strings are listed in apps/*/i18n_content.py so
`makemessages` puts them in locale/<lang>/LC_MESSAGES/django.po, and the
templates run each name through that catalog (`{% trans exercise.name %}`).
The API returns the stored English names, so the app ships the same
translations to show what the web shows.

Re-run after an IronStack update that adds content or translations:

    python3 -I tools/content-i18n/generate.py ../IronStack

Only reads the IronStack checkout; nothing there is imported or executed.
"""

import ast
import json
import pathlib
import sys

CONTENT_MODULES = ["apps/exercises/i18n_content.py", "apps/programs/i18n_content.py"]
OUTPUT = pathlib.Path(__file__).resolve().parents[2] / "qml" / "js" / "content.js"


def msgids(module_path):
    """Every string literal passed to _() in the module's *_NAMES lists,
    in order. Descriptions and instructions are left out - long texts
    the app doesn't show yet."""
    tree = ast.parse(module_path.read_text(encoding="utf-8"))
    lists = [
        node.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id.endswith("_NAMES") for t in node.targets)
    ]
    found = []
    for node in (n for value in lists for n in ast.walk(value)):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "_"
            and node.args
            and isinstance(node.args[0], ast.Constant)
            and isinstance(node.args[0].value, str)
        ):
            found.append(node.args[0].value)
    return found


def unquote(line):
    # A .po string is a C-style quoted literal; JSON's escapes cover the
    # ones gettext writes (\" \\ \n \t).
    return json.loads(line)


def read_po(path):
    """{msgid: msgstr} for translated, non-fuzzy, singular entries."""
    catalog = {}
    entry = {}
    field = None
    fuzzy = False

    def flush():
        msgid = entry.get("msgid")
        msgstr = entry.get("msgstr")
        if msgid and msgstr and not fuzzy and "msgid_plural" not in entry:
            catalog[msgid] = msgstr

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line:
            flush()
            entry, field, fuzzy = {}, None, False
        elif line.startswith("#,"):
            fuzzy = fuzzy or "fuzzy" in line
        elif line.startswith("#"):
            continue
        elif line.startswith('"'):
            if field:
                entry[field] += unquote(line)
        else:
            keyword, _, rest = line.partition(" ")
            field = keyword
            entry[field] = unquote(rest)
    flush()
    return catalog


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    wanted = []
    for module in CONTENT_MODULES:
        for msgid in msgids(root / module):
            if msgid not in wanted:
                wanted.append(msgid)

    languages = {}
    for po in sorted(root.glob("locale/*/LC_MESSAGES/django.po")):
        language = po.parts[-3]
        if language == "en":
            continue
        catalog = read_po(po)
        translated = {m: catalog[m] for m in wanted if catalog.get(m) and catalog[m] != m}
        if translated:
            languages[language] = translated

    version = (root / "VERSION").read_text(encoding="utf-8").strip()
    body = json.dumps(languages, ensure_ascii=False, indent=1, sort_keys=True)
    OUTPUT.write_text(
        ".pragma library\n\n"
        "// Generated by tools/content-i18n/generate.py from IronStack "
        + version
        + " - do not edit.\n"
        "// Built-in content names as the IronStack web shows them, by language.\n\n"
        "var catalog = " + body + "\n",
        encoding="utf-8",
    )
    counts = ", ".join(f"{lang} {len(names)}" for lang, names in languages.items())
    print(f"{OUTPUT}: {len(wanted)} names; {counts}")


if __name__ == "__main__":
    main()
